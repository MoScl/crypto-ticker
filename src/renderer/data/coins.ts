/** 按符号或名称模糊搜索，返回前 limit 条（自动补充主流榜的 CoinGecko id） */
export function searchCoins(query: string, limit = 12): CoinInfo[] {
  const q = query.trim().toLowerCase();
  const base = q ? COIN_LIST.filter((c) => c.symbol.toLowerCase().includes(q) || c.name.toLowerCase().includes(q)) : COIN_LIST;
  return base.slice(0, limit).map(withCoingeckoId);
}

/** 按符号精确反查（用于添加时补全名称 / CoinGecko id） */
export function findCoin(symbol: string): CoinInfo | undefined {
  const s = symbol.trim().toUpperCase();
  const base = COIN_LIST.find((c) => c.symbol === s);
  if (base) return withCoingeckoId(base);
  return MAINSTREAM_COINS.find((c) => c.symbol === s);
}

/** 从主流榜补充 CoinGecko id（id 均经 API 实测验证） */
function withCoingeckoId(c: CoinInfo): CoinInfo {
  if (c.coingeckoId) return c;
  const main = MAINSTREAM_COINS.find((m) => m.symbol === c.symbol);
  return main ? { ...c, coingeckoId: main.coingeckoId } : c;
}

